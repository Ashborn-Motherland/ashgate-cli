export function middleware(request: NextRequest) {
  const { pathname } = request.nextUrl;
  const isProtected = PROTECTED_PATHS.some((p) => pathname.startsWith(p));

  if (!isProtected) return NextResponse.next();

  // Vérifier le token de session (adaptez à votre auth : NextAuth, Keycloak, JWT cookie...)
  const token = request.cookies.get('auth_token')?.value
    ?? request.headers.get('authorization')?.replace('Bearer ', '');

  if (!token) {
    return NextResponse.redirect(new URL('/login?from=' + pathname, request.url));
  }

  // TODO: décoder le JWT et vérifier l'abonnement
  // const payload = decodeJwt(token);
  // if (!payload.subscription || payload.subscription === 'sandbox_only') {
  //   return NextResponse.redirect(new URL('/pricing', request.url));
  // }

  return NextResponse.next();
}

