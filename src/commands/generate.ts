type DetectedFramework = 'Flutter' | 'React (NextJS)' | 'Vue (Nuxt)' | 'React (Vite)' | 'Vue (Vite)' | 'Inconnu';

function detectFramework(cwd: string): DetectedFramework {
  const pubspec = path.join(cwd, 'pubspec.yaml');
  if (fs.existsSync(pubspec)) {
    return 'Flutter';
  }
  const pkgPath = path.join(cwd, 'package.json');
  if (fs.existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
      const deps = { ...pkg.dependencies, ...pkg.devDependencies };
      if (deps['nuxt']) return 'Vue (Nuxt)';
      if (deps['next']) return 'React (NextJS)';
      if (deps['@vitejs/plugin-react'] || deps['react']) return 'React (Vite)';
      if (deps['@vitejs/plugin-vue'] || deps['vue']) return 'Vue (Vite)';
    } catch { /* ignore */ }
  }
  return 'Inconnu';
}

