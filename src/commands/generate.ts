function toPascalCase(slug: string): string {
  return slug.split(/[-_]/).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');
}

export function registerGenerateCommand(program: Command): void {
  const generate = program.command('generate').description('Générateur de code (Paiements, SaaS, et Widgets)');

  generate
    .command('widget')
    .description('Générer un widget de paiement (Flutter, React, Vue…)')
    .action(async () => {
      console.log(chalk.bold('\n🎨 Générateur de widget de paiement\n'));

      // ── Détection automatique du framework ──
      const detected = detectFramework(process.cwd());
      if (detected !== 'Inconnu') {
        console.log(chalk.dim(`  Projet détecté : ${chalk.green(detected)}\n`));
      }

      const defaultFrameworkIdx = WIDGET_FRAMEWORKS.findIndex((f) => f.value === detected);

      // ── Questions communes ──
      const baseAnswers = await inquirer.prompt([
        {
          type: 'list',
          name: 'framework',
          message: 'Framework cible :',
          choices: WIDGET_FRAMEWORKS,
          default: defaultFrameworkIdx >= 0 ? WIDGET_FRAMEWORKS[defaultFrameworkIdx].value : 'Flutter',
        },
        { type: 'input', name: 'name', message: 'Nom du composant (ex: MyShop) :', validate: (v: string) => v.length > 0 },
        { type: 'input', name: 'projectKey', message: 'Project Key (x-feda-project-key) :' },
      ]);

      // ── Questions spécifiques Flutter ──
      let operators: string[] = ['mtn_open', 'moov'];
      let widgetType = 'bottom-sheet';
      let primaryColor = '#2196F3';

      if (baseAnswers.framework === 'Flutter') {
        const flutterAnswers = await inquirer.prompt([
          {
            type: 'list',
            name: 'type',
            message: 'Type de widget Flutter :',
            choices: [
              { name: '📱 Bottom Sheet de paiement (recommandé)', value: 'bottom-sheet' },
              { name: '🔘 Bouton de paiement inline', value: 'pay-button' },
            ],
          },
          {
            type: 'checkbox',
            name: 'operators',
            message: 'Opérateurs supportés :',
            choices: OPERATORS,
            validate: (v: string[]) => v.length > 0 || 'Sélectionnez au moins un opérateur',
          },
          {
            type: 'input',
            name: 'primaryColor',
            message: 'Couleur principale (hex) :',
            default: '#2196F3',
            validate: (v: string) => /^#[0-9A-Fa-f]{6}$/.test(v) || 'Format hex invalide (ex: #2196F3)',
          },
        ]);
        widgetType = flutterAnswers.type;
        operators = flutterAnswers.operators as string[];
        primaryColor = flutterAnswers.primaryColor as string;
      }

      // ── Questions spécifiques Web (React/Vue) ──
      let cssFramework = 'tailwind';
      if (baseAnswers.framework !== 'Flutter') {
        const webAnswers = await inquirer.prompt([
          {
            type: 'list',
            name: 'cssFramework',
            message: 'Librairie CSS :',
            choices: [
              { name: 'Tailwind CSS', value: 'tailwind' },
              { name: 'CSS Modules', value: 'modules' },
              { name: 'Aucune (styles inline)', value: 'inline' },
            ],
          },
        ]);
        cssFramework = webAnswers.cssFramework;
      }

      // ── Répertoire de sortie ──
      const defaultOutputDir = baseAnswers.framework === 'Flutter' ? 'lib/widgets' : 'src/components';
      const { outputDir } = await inquirer.prompt([
        { type: 'input', name: 'outputDir', message: 'Répertoire de sortie :', default: defaultOutputDir },
      ]);

      const spinner = ora('Génération du widget...').start();

      const fw: string = baseAnswers.framework;
      const isFlutter = fw === 'Flutter';
      const isVue = fw.startsWith('Vue');
      const isReact = fw.startsWith('React');

      // ── Génération du code ──
      let code: string;
      let filename: string;

      if (isFlutter) {
        const baseName = baseAnswers.name.toLowerCase().replace(/\s+/g, '_');
        filename = widgetType === 'bottom-sheet'
          ? `${baseName}_payment_bottom_sheet.dart`
          : `${baseName}_pay_button.dart`;
        code = widgetType === 'bottom-sheet'
          ? generateBottomSheet({ name: baseAnswers.name, projectKey: baseAnswers.projectKey, operators, primaryColor })
          : generatePayButton({ name: baseAnswers.name, projectKey: baseAnswers.projectKey, operators, primaryColor });
      } else if (isVue) {
        filename = `${toPascalCase(baseAnswers.name)}PaymentWidget.vue`;
        code = generateVuePaymentWidget({ name: baseAnswers.name, projectKey: baseAnswers.projectKey, cssFramework });
      } else {
        // React (NextJS ou Vite)
        filename = `${toPascalCase(baseAnswers.name)}PaymentWidget.tsx`;
        code = generateReactPaymentWidget({ name: baseAnswers.name, projectKey: baseAnswers.projectKey, cssFramework });
      }

      const outputPath = path.join(process.cwd(), outputDir as string, filename);
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, code, 'utf8');

      spinner.succeed(`Widget généré !`);
      console.log(`\n  Fichier : ${chalk.cyan(outputPath)}`);

      // ── Instructions d'intégration selon le framework ──
      console.log(chalk.bold('\n📋 Prochaines étapes d\'intégration :'));

      if (isFlutter) {
        console.log(chalk.yellow('\n  1. Ajoutez le SDK à votre pubspec.yaml :'));
        console.log(chalk.cyan('     dependencies:'));
        console.log(chalk.cyan('       feda_flutter: ^0.2.2'));
        console.log(chalk.dim('     (puis lancez : flutter pub get)'));
        console.log(chalk.yellow('\n  2. Initialisez le SDK dans votre main.dart :'));
        console.log(chalk.cyan(`     void main() {`));
        console.log(chalk.cyan(`       FedaFlutter.applyCloudConfig(`));
        console.log(chalk.cyan(`         projectKey: '${baseAnswers.projectKey}',`));
        console.log(chalk.cyan(`         cloudUrl: 'https://VOTRE_INSTANCE_ASH_BWALLET',`));
        console.log(chalk.cyan(`         environment: ApiEnvironment.sandbox,`));
        console.log(chalk.cyan(`       );`));
        console.log(chalk.cyan(`       runApp(const MyApp());`));
        console.log(chalk.cyan(`     }`));
        console.log(chalk.dim(`     Import : import 'package:feda_flutter/feda_flutter.dart';`));
        console.log(chalk.yellow('\n  3. Utilisez le widget dans votre code :'));
        const widgetClass = `${toPascalCase(baseAnswers.name)}${widgetType === 'bottom-sheet' ? 'PaymentBottomSheet' : 'PayButton'}`;
        if (widgetType === 'bottom-sheet') {
          console.log(chalk.cyan(`     ${widgetClass}.show(context, amount: 2500, description: 'Commande #42');`));
        } else {
          console.log(chalk.cyan(`     ${widgetClass}(amount: 2500, description: 'Commande #42', phoneNumber: '+22960000000', operator: 'moov')`));
        }
      } else {
        const pkgInstall = fw.includes('Nuxt') ? 'npm install feda-js' : 'npm install feda-js';
        console.log(chalk.yellow('\n  1. Installez le SDK JS :'));
        console.log(chalk.cyan(`     ${pkgInstall}`));
        console.log(chalk.dim('     (ou configurez le proxy cloud directement via fetch/axios)'));
        console.log(chalk.yellow('\n  2. Configurez les variables d\'environnement :'));
        const envPrefix = fw.includes('Nuxt') ? 'NUXT_PUBLIC' : 'NEXT_PUBLIC';
        console.log(chalk.cyan(`     ${envPrefix}_FEDA_PROJECT_KEY=${baseAnswers.projectKey}`));
        console.log(chalk.cyan(`     ${envPrefix}_FEDA_CLOUD_URL=https://VOTRE_INSTANCE_ASH_BWALLET`));
        console.log(chalk.yellow('\n  3. Importez et utilisez le composant :'));
        if (isVue) {
          console.log(chalk.cyan(`     import ${toPascalCase(baseAnswers.name)}PaymentWidget from '~/components/${filename}';`));
        } else {
          console.log(chalk.cyan(`     import { ${toPascalCase(baseAnswers.name)}PaymentWidget } from './components/${filename}';`));
          console.log(chalk.cyan(`     <${toPascalCase(baseAnswers.name)}PaymentWidget amount={2500} description="Commande #42" />`));
        }
      }
    });

  generate
    .command('pricing-page')
    .description('Générer une page de Tarifs SaaS (Pricing Page) connectée à votre configuration')
    .action(async () => {
      console.log(chalk.bold('\n🛒 Générateur de Pricing Page SaaS\n'));

      const detected = detectFramework(process.cwd());
      const detectedLabel = detected === 'Flutter' ? 'Flutter'
        : detected.includes('Nuxt') ? 'Nuxt (Vue)'
        : detected.includes('NextJS') ? 'NextJS (React)'
        : detected.includes('Vite') && detected.includes('Vue') ? 'Vue (Vite)'
        : detected.includes('Vite') ? 'React (Vite)'
        : null;
      if (detectedLabel) console.log(chalk.dim(`  Projet détecté : ${chalk.green(detected)}\n`));

      const answers = await inquirer.prompt([
        {
          type: 'list',
          name: 'framework',
          message: 'Framework cible :',
          choices: ['Flutter', 'NextJS (React)', 'React (Vite)', 'Nuxt (Vue)', 'Vue (Vite)', 'Laravel'],
          default: detectedLabel ?? 'Flutter',
        },
        { type: 'input', name: 'outputDir', message: 'Répertoire de sortie :', default: './components' },
      ]);
      const spinner = ora('Génération de la page de tarifs...').start();

      const isVue = answers.framework.includes('Vue') || answers.framework.includes('Nuxt');
      const isReact = answers.framework.includes('React') || answers.framework.includes('NextJS');
      const filename = answers.framework === 'Flutter' ? 'pricing_page.dart'
        : isVue ? 'PricingPage.vue'
        : answers.framework === 'Laravel' ? 'pricing-page.blade.php'
        : 'PricingPage.tsx';

      let pricingCode: string;
      if (answers.framework === 'Flutter') {
        pricingCode = generateFlutterPricingPage();
      } else if (isVue) {
        pricingCode = generateNuxtPricingPage();
      } else if (isReact) {
        pricingCode = generateNextPricingPage();
      } else {
        pricingCode = `{{-- Generated by wallet-cli --}}\n{{-- Laravel Pricing Page --}}\n<section class="pricing">\n  <h2>Nos offres</h2>\n  {{-- TODO: loop sur $plans depuis votre controller --}}\n</section>\n`;
      }

      const outputPath = path.join(process.cwd(), answers.outputDir, filename);
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, pricingCode, 'utf8');

      spinner.succeed(`Pricing Page générée pour ${answers.framework} !`);
      console.log(`\n  Fichier : ${chalk.cyan(outputPath)}`);
      console.log(chalk.dim('  Le code récupère dynamiquement vos plans via GET /billing/plans.'));
    });

  generate
    .command('customer-portal')
    .description('Générer un Portail Client SaaS (Customer Portal)')
    .action(async () => {
      console.log(chalk.bold('\n👤 Générateur de Customer Portal SaaS\n'));

      const detected = detectFramework(process.cwd());
      const detectedLabel = detected === 'Flutter' ? 'Flutter'
        : detected.includes('Nuxt') ? 'Nuxt (Vue)'
        : detected.includes('NextJS') ? 'NextJS (React)'
        : detected.includes('Vite') && detected.includes('Vue') ? 'Vue (Vite)'
        : detected.includes('Vite') ? 'React (Vite)'
        : null;
      if (detectedLabel) console.log(chalk.dim(`  Projet détecté : ${chalk.green(detected)}\n`));

      const answers = await inquirer.prompt([
        {
          type: 'list',
          name: 'framework',
          message: 'Framework cible :',
          choices: ['Flutter', 'NextJS (React)', 'React (Vite)', 'Nuxt (Vue)', 'Vue (Vite)', 'Laravel'],
          default: detectedLabel ?? 'Flutter',
        },
        { type: 'input', name: 'outputDir', message: 'Répertoire de sortie :', default: './components' },
      ]);
      const spinner = ora('Génération du portail client...').start();

      const isVue = answers.framework.includes('Vue') || answers.framework.includes('Nuxt');
      const isReact = answers.framework.includes('React') || answers.framework.includes('NextJS');

      let portalCode: string;
      if (answers.framework === 'Flutter') {
        portalCode = generateFlutterCustomerPortal();
      } else if (isVue) {
        portalCode = generateNuxtCustomerPortal();
      } else if (isReact) {
        portalCode = generateNextCustomerPortal();
      } else {
        portalCode = `{{-- Generated by wallet-cli --}}\n{{-- Laravel Customer Portal --}}\n<div class="portal">\n  {{-- TODO: afficher les abonnements de l'utilisateur --}}\n</div>\n`;
      }

      const filename = answers.framework === 'Flutter' ? 'customer_portal.dart'
        : isVue ? 'CustomerPortal.vue'
        : answers.framework === 'Laravel' ? 'customer-portal.blade.php'
        : 'CustomerPortal.tsx';

      const outputPath = path.join(process.cwd(), answers.outputDir, filename);
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, portalCode, 'utf8');

      spinner.succeed(`Customer Portal généré pour ${answers.framework} !`);
      console.log(`\n  Fichier : ${chalk.cyan(outputPath)}`);
    });

  generate
    .command('guard')
    .description('Générer un Guard / Middleware de protection SaaS')
    .action(async () => {
      console.log(chalk.bold('\n🛡️ Générateur de protection SaaS (Guard/Middleware)\n'));

      const detected = detectFramework(process.cwd());
      const detectedGuard = detected === 'Flutter' ? 'Flutter (GoRouter)'
        : detected.includes('NextJS') || (detected.includes('React') && detected.includes('Vite')) ? 'NextJS (Middleware)'
        : null;
      if (detectedGuard) console.log(chalk.dim(`  Projet détecté : ${chalk.green(detected)}\n`));

      const answers = await inquirer.prompt([
        {
          type: 'list',
          name: 'framework',
          message: 'Framework cible :',
          choices: ['Flutter (GoRouter)', 'NestJS', 'NextJS (Middleware)', 'Nuxt (middleware)', 'Laravel'],
          default: detectedGuard ?? 'Flutter (GoRouter)',
        },
        { type: 'input', name: 'outputDir', message: 'Répertoire de sortie :', default: './guards' },
      ]);
      const spinner = ora('Génération du système de protection...').start();

      const filename = answers.framework.includes('Flutter') ? 'saas_guard.dart'
        : answers.framework.includes('NestJS') ? 'saas.guard.ts'
        : answers.framework.includes('Laravel') ? 'SaasMiddleware.php'
        : answers.framework.includes('Nuxt') ? 'saas.middleware.ts'
        : 'middleware.ts';

      const outputPath = path.join(process.cwd(), answers.outputDir, filename);
      let guardCode: string;
      if (answers.framework.includes('Flutter')) {
        guardCode = generateFlutterGuard();
      } else if (answers.framework.includes('NestJS')) {
        guardCode = generateNestJsGuard();
      } else if (answers.framework.includes('Laravel')) {
        guardCode = `<?php\n// Generated by wallet-cli\nnamespace App\\Http\\Middleware;\nuse Closure;\nuse Illuminate\\Http\\Request;\n\nclass SaasSubscriptionMiddleware\n{\n    public function handle(Request $request, Closure $next)\n    {\n        $user = $request->user();\n        if (!$user || !$user->hasActiveSubscription()) {\n            return response()->json(['error' => 'Subscription required'], 403);\n        }\n        return $next($request);\n    }\n}\n`;
      } else if (answers.framework.includes('Nuxt')) {
        guardCode = generateNuxtGuard();
      } else {
        guardCode = generateNextJsGuard();
      }
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, guardCode, 'utf8');

      spinner.succeed(`Guard SaaS généré pour ${answers.framework} !`);
      console.log(`\n  Fichier : ${chalk.cyan(outputPath)}`);
    });
}
